// scaffold.js — `mcp-flow init`: connect to a server, introspect its tools,
// and write a ready-to-edit first flow. Your first test, written for you.

'use strict';

import fs from 'node:fs';
import path from 'node:path';
import { McpClient, createTransport } from './client.js';
import { UserError } from './util.js';

/**
 * Build plausible sample arguments from a JSON-schema-ish inputSchema.
 * Only required properties get values — minimal, least-surprise calls.
 */
export function sampleArgs(tool) {
  const schema = tool.inputSchema;
  const args = {};
  if (!schema || typeof schema !== 'object') return { args, todos: [] };
  const props = schema.properties && typeof schema.properties === 'object' ? schema.properties : {};
  const required = Array.isArray(schema.required) ? schema.required : Object.keys(props);
  for (const name of required) {
    const { value, isTodo } = sampleValue(name, props[name] || {});
    args[name] = value;
    if (isTodo) args[name] = `TODO_${name}`;
  }
  return { args, todos: Object.keys(args).filter((k) => String(args[k]).startsWith('TODO_')) };
}

function sampleValue(name, prop) {
  if (prop.default !== undefined) return { value: prop.default, isTodo: false };
  if (Array.isArray(prop.enum) && prop.enum.length) return { value: prop.enum[0], isTodo: false };
  if (Array.isArray(prop.examples) && prop.examples.length) return { value: prop.examples[0], isTodo: false };
  switch (prop.type) {
    case 'string': {
      const fmt = String(prop.format || '');
      if (fmt.includes('date')) return { value: new Date().toISOString().slice(0, 10), isTodo: false };
      if (fmt.includes('time')) return { value: new Date().toISOString(), isTodo: false };
      if (fmt.includes('email')) return { value: 'user@example.com', isTodo: false };
      if (fmt.includes('uri') || fmt === 'url') return { value: 'https://example.com', isTodo: false };
      return { value: null, isTodo: true };
    }
    case 'integer':
    case 'number':
      return { value: 1, isTodo: false };
    case 'boolean':
      return { value: true, isTodo: false };
    case 'array':
      return { value: [], isTodo: false };
    case 'object': {
      const inner = {};
      let innerTodo = false;
      const props = prop.properties || {};
      for (const [k, v] of Object.entries(props)) {
        if (!prop.required || prop.required.includes(k)) {
          const r = sampleValue(k, v || {});
          if (r.isTodo) { inner[k] = `TODO_${k}`; innerTodo = true; }
          else inner[k] = r.value;
        }
      }
      return { value: inner, isTodo: innerTodo };
    }
    default:
      return { value: null, isTodo: true };
  }
}

/**
 * Introspect the server and generate flow + config files.
 * @returns {{ files: {path:string, content:string}[], tools: object[], skipped: string[] }}
 */
export async function generateInit({ serverSpec, outDir = process.cwd(), maxTools = 3, flowName = 'smoke' }) {
  const transport = createTransport(serverSpec);
  const client = new McpClient(transport, { timeoutMs: 30000 });
  try {
    transport.start?.();
    await client.initialize();
    const tools = await client.listTools();
    if (!tools.length) {
      throw new UserError('This server exposes no tools — nothing to generate a flow for');
    }
    // Prefer read-only tools for the first flow; destructive tools are opt-in.
    const safe = tools.filter((t) => !t.annotations || t.annotations.readOnlyHint !== false);
    const picked = safe.slice(0, maxTools);
    const skipped = tools.filter((t) => !picked.includes(t)).map((t) => t.name);

    const steps = [];
    const todos = [];
    picked.forEach((t, i) => {
      const { args, todos: argTodos } = sampleArgs(t);
      const step = { call: t.name };
      if (Object.keys(args).length) step.args = args;
      step.expect = { ok: true };
      steps.push(step);
      for (const key of argTodos) todos.push(`step ${i + 1} (${t.name}): replace "TODO_${key}" with a real value`);
    });

    const flow = {
      name: flowName,
      description: `Smoke test generated by mcp-flow init for ${client.serverInfo?.name || 'server'}`,
      steps,
    };
    if (todos.length) flow.todo = todos;

    const files = [
      { path: path.join(outDir, 'flows', 'smoke.flow.json'), content: JSON.stringify(flow, null, 2) + '\n' },
    ];
    const configPath = path.join(outDir, 'mcp-flow.json');
    if (!fs.existsSync(configPath)) {
      const config = { flows: 'flows/**/*.flow.json' };
      config.server = serverSpec.url
        ? { url: serverSpec.url }
        : { command: serverSpec.command, args: serverSpec.args || [] };
      files.push({ path: configPath, content: JSON.stringify(config, null, 2) + '\n' });
    }
    return { files, tools, skipped, serverInfo: client.serverInfo, protocolVersion: client.protocolVersion };
  } finally {
    await client.close().catch(() => {});
  }
}
